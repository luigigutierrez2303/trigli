export function flagsOfItems(names: string[]): Record<string, boolean> {
  const out: Record<string, boolean> = {};
  for (const name of names) {
    const flag = FOODS.find((f) => f.name === name)?.flag;
    if (flag) out[flag] = true;
  }
  return out;
}
