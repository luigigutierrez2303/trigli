-- Catálogo base de alimentos (global, solo lectura) y ajustes por usuario.
-- El usuario no edita el base: agrega alimentos propios, pisa uno del base (mismo nombre) u oculta uno.
create table food (
  id       uuid primary key default gen_random_uuid(),
  name     text not null unique check (char_length(name) between 1 and 80),
  cat      text not null,
  portion  text not null,
  kcal     integer not null check (kcal between 0 and 5000),
  protein  numeric not null default 0 check (protein >= 0),
  grams    integer check (grams > 0),
  flag     text
);

alter table food enable row level security;
create policy read_all on food for select to authenticated using (true);
revoke insert, update, delete on food from authenticated;

create table user_food (
  id       uuid primary key default gen_random_uuid(),
  user_id  uuid not null default auth.uid() references auth.users on delete cascade,
  name     text not null check (char_length(name) between 1 and 80),
  cat      text not null,
  portion  text not null check (char_length(portion) between 1 and 60),
  kcal     integer not null check (kcal between 0 and 5000),
  protein  numeric not null default 0 check (protein >= 0),
  grams    integer check (grams > 0),
  flag     text,
  -- true: oculta del buscador el alimento del base con este nombre
  hidden   boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

alter table user_food enable row level security;
create policy own_rows on user_food for all using (user_id = auth.uid()) with check (user_id = auth.uid());

